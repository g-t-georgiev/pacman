/// <reference types="node" />
// The versions shown in the README and the manual, generated from their sources so they can't
// go stale (a test and the pre-commit hook check them):
//   vp run docs:versions   rewrite the generated blocks
//   vp run docs:check      fail if a block is out of date (what the hook and the test do)
//
// Sources: package.json (the game's version, bun), the installed packages (the tools), the
// rules / saved state / replay format constants, and the CI workflow (Node.js).
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { REPLAY_FORMAT_VERSION, RULES_VERSION } from "../src/game/replay";
import { GAME_STATE_VERSION } from "../src/game/gameState";

const read = (path: string) => readFileSync(path, "utf8");
const installed = (pkg: string): string =>
  (JSON.parse(read(`node_modules/${pkg}/package.json`)) as { version: string }).version;

interface PackageJson {
  version: string;
  packageManager?: string;
}

/** Everything the README's versions table lists, from its source. */
export function collectVersions() {
  const pkg = JSON.parse(read("package.json")) as PackageJson;
  const ci = /node-version:\s*"?([\d.]+)"?/.exec(read(".github/workflows/ci.yml"))?.[1] ?? "?";
  return {
    game: pkg.version,
    rules: RULES_VERSION,
    state: GAME_STATE_VERSION,
    replayFormat: REPLAY_FORMAT_VERSION,
    vitePlus: installed("vite-plus"),
    vitest: installed("vitest"),
    playwright: installed("playwright"),
    typescript: installed("typescript"),
    react: installed("react"),
    tailwind: installed("tailwindcss"),
    marked: installed("marked"),
    highlight: installed("highlight.js"),
    node: ci,
    bun: pkg.packageManager?.replace(/^bun@/, "") ?? "?",
  };
}

const START = "<!-- versions:start (generated by `vp run docs:versions`; checked by a test) -->";
const END = "<!-- versions:end -->";

/** The README's block: what it describes, and every version. */
export function readmeBlock(): string {
  const v = collectVersions();
  const rows: Array<[string, string]> = [
    ["Game", v.game],
    ["Manual (in the game and in `docs/manual/`)", `${v.game}: it describes this game version`],
    ["Rules: what a frame does (replays record it)", String(v.rules)],
    ["Saved state: its shape (replays record it)", String(v.state)],
    ["Replay files: their format", String(v.replayFormat)],
    ["Vite+: dev server, build, lint, format", v.vitePlus],
    ["Vitest: the tests", v.vitest],
    ["Playwright: the browser tests (Chromium)", v.playwright],
    ["TypeScript", v.typescript],
    ["React", v.react],
    ["Tailwind CSS", v.tailwind],
    ["marked and highlight.js: the manual's page", `${v.marked} and ${v.highlight}`],
    ["Node.js: CI", v.node],
    ["bun: package manager", v.bun],
  ];
  return [
    START,
    "",
    `This README describes **Pac-Man Arcade Lab ${v.game}**.`,
    "",
    "| What | Version |",
    "| :--- | :------ |",
    ...rows.map(([what, version]) => `| ${what} | ${version} |`),
    "",
    END,
  ].join("\n");
}

/** The manual's line: which game version it describes. */
export function manualBlock(): string {
  const v = collectVersions();
  return [
    START,
    "",
    `This manual describes **Pac-Man Arcade Lab ${v.game}** (rules version ${v.rules}, saved state version ${v.state}).`,
    "",
    END,
  ].join("\n");
}

/** The files with a generated block, and what the block should be. */
export const TARGETS: Array<{ file: string; block: () => string }> = [
  { file: "README.md", block: readmeBlock },
  { file: "docs/manual/01-introduction.md", block: manualBlock },
];

/** A file's text with its block replaced (its markers must be there already). */
export function withBlock(text: string, block: string, file: string): string {
  const a = text.indexOf("<!-- versions:start");
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${file}: no <!-- versions:start --> ... ${END} markers`);
  return text.slice(0, a) + block + text.slice(b + END.length);
}

/** A file's current block (between the markers), or null without markers. */
function currentBlock(text: string): string | null {
  const a = text.indexOf("<!-- versions:start");
  const b = text.indexOf(END);
  return a < 0 || b < a ? null : text.slice(a, b + END.length);
}

/**
 * A block as content, not layout: the formatter re-pads Markdown tables on every commit, so
 * spacing and the separator row's dashes don't count.
 */
function normalized(block: string): string {
  return block
    .split("\n")
    .map((line) =>
      line
        .trim()
        .replace(/\s+/g, " ")
        .replace(/ ?\| ?/g, "|")
        .replace(/-+/g, "-")
    )
    .filter((line) => line !== "")
    .join("\n");
}

/** Files whose generated block is missing or out of date. */
export function outdatedFiles(): string[] {
  return TARGETS.filter(({ file, block }) => {
    const current = currentBlock(read(file));
    return current === null || normalized(current) !== normalized(block());
  }).map((t) => t.file);
}

// Run as a script
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  const outdated = outdatedFiles();
  if (check) {
    if (outdated.length > 0) {
      console.error(
        `Versions out of date in: ${outdated.join(", ")}. Run \`vp run docs:versions\` and commit the result.`
      );
      process.exit(1);
    }
    console.log("Versions in the README and the manual are up to date.");
  } else {
    // Only the files that changed, then formatted, so the tables keep their column padding
    for (const { file, block } of TARGETS) {
      if (outdated.includes(file)) writeFileSync(file, withBlock(read(file), block(), file));
    }
    if (outdated.length > 0) {
      // One command string: the paths are this script's own (TARGETS), with no spaces
      execSync(`vp fmt ${outdated.join(" ")}`, { stdio: "inherit" });
    }
    console.log(outdated.length > 0 ? `Updated: ${outdated.join(", ")}` : "Already up to date.");
  }
}
